# ── 화면 배율 (고해상도 모니터 대응) ─────────────────────
#
# ⚠️ 이걸 왜 두는가 — 실제로 겪은 문제:
# Tkinter는 **글꼴만** 화면 DPI에 맞춰 자동으로 키워준다. 글꼴 크기는 '포인트' 단위라
# 125% 배율 화면에서는 알아서 1.25배로 커진다. 그런데 캔버스에 그리는 도형·여백은
# 전부 '픽셀' 단위라 그대로 있는다.
#
# 결과: 글자만 커지고 아이콘·막대·패널은 그대로여서 화면이 쪼그라들고 빽빽해 보인다.
# (개발용 96 DPI 모니터에서는 SCALE=1.0 이라 아무 일도 일어나지 않으므로 눈치채기 어렵다)
#
# 그래서 픽셀 값은 전부 px() 를 거치게 해서 글꼴과 같은 비율로 함께 키운다.
BASE_DPI = 96.0         # 이 화면 기준으로 아래 숫자들을 정했다
SCALE = 1.0             # init_scaling() 이 실제 DPI를 보고 다시 정한다

# ── 입체감 수치 (전부 96 DPI 기준. 실제 사용 시 px() 를 통과한다) ──
# 그림자를 얼마나 밀고 얼마나 흐리게 할지. 값이 크면 과장돼 보이고,
# 작으면 밋밋해진다. 아래 값이 작은 위젯에 잘 어울리는 정도로 맞춘 것.
SHADOW_OFFSET = 3       # 그림자를 미는 거리(px)
SHADOW_BLUR = 5         # 그림자를 흐리는 정도
RADIUS_SMALL = 10       # 버튼처럼 작은 요소의 모서리
RADIUS_LARGE = 16       # 패널처럼 큰 요소의 모서리


def px(value: float) -> int:
    """96 DPI 기준으로 정한 픽셀 값을 지금 화면 배율에 맞게 바꾼다.

    화면에 그리는 모든 크기·여백은 이 함수를 통과해야 한다.
    (글꼴 크기는 예외 — Tkinter가 이미 알아서 키워준다. 여기서 또 키우면 두 배가 된다)
    """
    return int(round(value * SCALE))


def unpx(value: float) -> float:
    """px() 의 반대. 실제 픽셀 값을 96 DPI 기준 값으로 되돌린다.

    글꼴 너비를 재는 곳에서만 쓴다. Tkinter가 알려주는 글자 너비는 **실제 픽셀**인데,
    그걸 다시 px() 에 넣으면 배율이 두 번 곱해지기 때문이다.
    """
    return value / SCALE


def init_scaling(root) -> float:
    """창이 만들어진 뒤 한 번 불러서 화면 배율을 정한다.

    창이 있어야 화면 DPI를 물어볼 수 있어서 import 시점이 아니라 여기서 정한다.

    Args:
        root: Tk 창 (화면 정보를 물어볼 대상)

    Returns:
        정해진 배율. 96 DPI 화면이면 1.0
    """
    global SCALE
    try:
        dpi = float(root.winfo_fpixels("1i"))
    except Exception:
        return SCALE      # 화면 정보를 못 읽어도 기본값(1.0)으로 그냥 돌아간다

    # 상한을 두는 이유: 200%를 넘는 배율에서 창이 화면 밖으로 나가는 것을 막는다.
    # 하한이 1.0인 이유: 축소하면 선이 1픽셀 밑으로 내려가 오히려 더 깨져 보인다.
    SCALE = max(1.0, min(2.0, dpi / BASE_DPI))
    return SCALE
