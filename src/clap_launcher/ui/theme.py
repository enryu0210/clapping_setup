BG_SUNKEN = "#e3e6ee"   # 움푹 들어간 영역의 바닥 (아주 살짝 어둡게)

# ── 글자 ─────────────────────────────────────────────────
FG = "#3d4457"          # 본문
FG_MUTED = "#8790a5"    # 설명글처럼 덜 중요한 글자
FG_ON_ACCENT = "#ffffff"

# ── 강조색 (꼭 필요한 곳에만 아껴 쓴다) ───────────────────
ACCENT = "#5b7cfa"      # 주요 동작
