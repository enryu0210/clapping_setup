"""뉴모피즘(Neumorphism) 색과 글꼴 — 화면 전체가 여기 한 곳을 본다.

뉴모피즘이 뭔가:
"배경과 같은 색의 덩어리가 배경에서 눌리거나 튀어나온 것처럼" 보이게 하는 방식이다.
버튼에 색을 칠해서 구분하는 게 아니라 **그림자만으로** 입체감을 만든다.

  튀어나옴(raised) : 왼쪽 위에 밝은 그림자, 오른쪽 아래에 어두운 그림자
  들어감(inset)    : 그 반대. 안쪽에 그림자가 진다

그래서 색이 세 개만 있으면 된다 — 바탕색, 밝은 그림자, 어두운 그림자.
이 세 색은 반드시 **같은 계열**이어야 한다. 색이 튀면 뉴모피즘 느낌이 깨진다.

⚠️ 배경색은 순수한 흰색이나 검정이면 안 된다.
   흰색이면 '더 밝은' 그림자를 만들 수 없고, 검정이면 '더 어두운' 그림자를 못 만든다.
   그래서 중간 밝기의 회색을 쓴다.
"""

